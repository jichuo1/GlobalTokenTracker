pub struct Devin;

fn cli_roots(home: Option<&Path>, native: Option<&Path>, xdg: Option<&Path>) -> Vec<PathBuf> {
    let mut roots = Vec::new();
    for base in [
        native.map(Path::to_path_buf),
        home.map(|p| p.join(".local/share")),
        xdg.filter(|p| p.is_absolute()).map(Path::to_path_buf),
    ]
    .into_iter()
    .flatten()
    {
        let root = base.join("devin/cli");
        if !roots.contains(&root) {
            roots.push(root);
        }
    }
    roots
}

fn roots() -> Vec<PathBuf> {
    let mut result = cli_roots(
        dirs::home_dir().as_deref(),
        dirs::data_dir().as_deref(),
        std::env::var_os("XDG_DATA_HOME")
            .map(PathBuf::from)
            .as_deref(),
    );
    if let Some(local) = dirs::data_local_dir() {
        result.push(local.join("devin/cli"));
    }
    if let Some(value) = std::env::var_os("DEVIN_SESSIONS_DIR").filter(|v| !v.is_empty()) {
        let configured = PathBuf::from(value);
        result.insert(0, configured.join("cli"));
        result.push(configured);
    }
    result.sort();
    result.dedup();
    result
}

fn discover_in(roots: &[PathBuf]) -> Vec<SourceItem> {
    let mut seen = HashSet::new();
    let mut items = Vec::new();
    for root in roots {
        let db = root.join("sessions.db");
        if db.is_file() && seen.insert(db.canonicalize().unwrap_or_else(|_| db.clone())) {
            items.push(SourceItem {
                key: db.to_string_lossy().into_owned(),
                path: db,
                kind: SourceKind::Sqlite,
            });
        }
        for path in crate::sync::collect_files(&root.join("sessions"), "jsonl", 3) {
            if path.file_name().is_some_and(|name| name == "log.jsonl")
                && seen.insert(path.canonicalize().unwrap_or_else(|_| path.clone()))
            {
                items.push(SourceItem {
                    key: path.to_string_lossy().into_owned(),
                    path,
                    kind: SourceKind::Jsonl,
                });
            }
        }
    }
    items
}

// Official devin 3000.11.205 folder store, generated by its offline SQLite
// importer: cli/sessions/<id>/{meta.json,log.jsonl}. Both stores may coexist.
fn folder_meta(item: &SourceItem) -> Result<Value> {
    let Some(parent) = item.path.parent() else {
        return Ok(Value::Null);
    };
    let path = parent.join("meta.json");
    if !path.is_file() {
        return Ok(Value::Null);
    }
    let bytes = std::fs::read(path)?;
    if bytes.len() > 1024 * 1024 {
        anyhow::bail!("Devin folder metadata exceeds scan limit");
    }
    let value: Value = serde_json::from_slice(&bytes)?;
    if value.get("v").is_some() && value["v"].as_u64() != Some(1) {
        anyhow::bail!("unsupported Devin folder metadata version");
    }
    Ok(value)
}

fn folder_identity(item: &SourceItem, sid: &str, node: &Value, message: &Value) -> Result<String> {
    if let Some(id) = text(&message["metadata"]["request_id"]) {
        return Ok(format!("devin:{id}"));
    }
    // A migrated row without request_id must keep the SQLite fallback key.
    if let Some(id) = node["id"].as_i64()
        && let Some(base) = item.path.ancestors().nth(3)
    {
        let path = base.join("sessions.db");
        if path.is_file() {
            let conn = super::opencode::open_ro(&path)?;
            let row: Option<(i64, Option<String>)> = conn.query_row(
                "SELECT row_id, CASE WHEN json_valid(chat_message) THEN json_extract(chat_message,'$.metadata.request_id') END
                 FROM message_nodes WHERE session_id=?1 AND node_id=?2",
                rusqlite::params![sid, id], |row| Ok((row.get(0)?, row.get(1)?))).optional()?;
            if let Some((row_id, request)) = row {
                return Ok(request.filter(|v| !v.is_empty()).map_or_else(
                    || format!("devin:{sid}:{row_id}"),
                    |id| format!("devin:{id}"),
                ));
            }
        }
    }
    if let Some(id) = text(&message["message_id"]) {
        return Ok(format!("devin:file-message:{id}"));
    }
    if let Some(id) = node["id"].as_i64() {
        return Ok(format!("devin:file:{sid}:{id}"));
    }
    anyhow::bail!("Devin folder usage has no stable request or node identity")
}

impl SourceAdapter for Devin {
    fn id(&self) -> &'static str {
        apps::DEVIN
    }
    fn display_name(&self) -> &'static str {
        "Devin"
    }
    fn capability(&self) -> Capability {
        Capability::Precise
    }

    fn watch_roots(&self) -> Vec<PathBuf> {
        roots()
    }

    fn discover(&self) -> Result<Vec<SourceItem>> {
        Ok(discover_in(&roots()))
    }

    fn parse_jsonl(
        &self,
        item: &SourceItem,
        from: u64,
        data: &[u8],
        _prior_state: Option<&str>,
    ) -> Result<ScanOutcome> {
        let (segment, consumed) = complete_lines(data);
        let mut out = ScanOutcome {
            consumed,
            ..Default::default()
        };
        let meta = folder_meta(item)?;
        let sid = text(&meta["id"])
            .or_else(|| {
                item.path
                    .parent()
                    .and_then(Path::file_name)
                    .map(|s| s.to_string_lossy().into_owned())
            })
            .unwrap_or_default();
        let mut offset = from;
        for line in segment.split(|&b| b == b'\n') {
            let start = offset;
            offset += line.len() as u64 + 1;
            let Ok(value) = serde_json::from_slice::<Value>(line) else {
                continue;
            };
            if value["kind"].as_str() != Some("node") {
                continue;
            }
            let node = &value["node"];
            let message = &node["message"];
            if message["role"].as_str() != Some("assistant") {
                continue;
            }
            let md = &message["metadata"];
            let metrics = &md["metrics"];
            if !metrics.is_object() {
                continue;
            }
            let model = text(&md["generation_model"]).or_else(|| text(&meta["model"]));
            let request_model = if model.as_deref() == Some("compactor") {
                None
            } else {
                text(&meta["model"])
            };
            out.events.push(UsageEvent {
                dedup_key: folder_identity(item, &sid, node, message)?,
                app: apps::DEVIN.into(),
                session_id: Some(sid.clone()),
                project: text(&meta["working_directory"]),
                model,
                request_model,
                ts_start: epoch_ms(&md["started_generation_at"])
                    .or_else(|| epoch_ms(&md["created_at"]))
                    .or_else(|| epoch_ms(&value["at"])),
                ts_end: epoch_ms(&md["created_at"]),
                input_tokens: num(&metrics["input_tokens"]),
                output_tokens: num(&metrics["output_tokens"]),
                cache_read_tokens: num(&metrics["cache_read_tokens"]),
                cache_write_5m_tokens: num(&metrics["cache_creation_tokens"]),
                ttft_ms: num_opt(&metrics["ttft_ms"]).and_then(|v| i64::try_from(v).ok()),
                duration_ms: num_opt(&metrics["total_time_ms"]).and_then(|v| i64::try_from(v).ok()),
                status: text(&md["finish_reason"]),
                credits: fnum(&md["acu_cost"]),
                provenance: Provenance::LocalJsonl,
                raw_ref: Some(format!("{}@{start}", item.path.display())),
                ..Default::default()
            });
        }
        Ok(out)
    }

    fn scan_sqlite(&self, item: &SourceItem, store: &Store) -> Result<ScanOutcome> {
        let cur = store.load_cursor(&item.key)?;
        let since = if cur.state.as_deref() == Some(METRICS_STATE) {
            cur.offset as i64
        } else {
            0 // One-time backfill under the same request identities.
        };
        let conn = super::opencode::open_ro(&item.path)?;
        let mut st = conn.prepare(
            // Extract only role + metadata; chat content can be megabytes.
            // Structural JSON access accepts all whitespace layouts and never
            // mistakes an embedded assistant message in tool content for usage.
            "SELECT n.row_id, n.session_id,
                    CASE WHEN json_valid(n.chat_message) THEN
                        json_extract(n.chat_message, '$.role', '$.metadata') END,
                    s.model, s.working_directory
             FROM message_nodes n
             LEFT JOIN sessions s ON s.id = n.session_id
             WHERE n.row_id > ?1
             ORDER BY n.row_id",
        )?;
        let rows = st.query_map(rusqlite::params![since], |r| {
            Ok((
                r.get::<_, i64>(0)?,
                r.get::<_, Option<String>>(1)?,
                r.get::<_, Option<String>>(2)?,
                r.get::<_, Option<String>>(3)?,
                r.get::<_, Option<String>>(4)?,
            ))
        })?;
        let mut out = ScanOutcome::default();
        let mut max_row = cur.offset as i64;
        for row in rows {
            let (row_id, session_id, msg_md, sess_model, workdir) = row?;
            max_row = max_row.max(row_id);
            let Some(msg_md) = msg_md else { continue };
            let Ok(message) = serde_json::from_str::<Value>(&msg_md) else {
                continue;
            };
            if message[0] != "assistant" {
                continue;
            }
            let md = &message[1];
            let metrics = &md["metrics"];
            if !metrics.is_object() {
                continue;
            }
            let rid = text(&md["request_id"])
                .unwrap_or_else(|| format!("{}:{row_id}", session_id.as_deref().unwrap_or("?")));
            let model = text(&md["generation_model"]).or_else(|| sess_model.clone());
            let request_model = if model.as_deref() == Some("compactor") {
                None
            } else {
                sess_model
            };
            out.events.push(UsageEvent {
                dedup_key: format!("devin:{rid}"),
                app: apps::DEVIN.into(),
                session_id,
                project: workdir,
                model,
                request_model,
                ts_start: epoch_ms(&md["started_generation_at"])
                    .or_else(|| epoch_ms(&md["created_at"])),
                ts_end: epoch_ms(&md["created_at"]),
                input_tokens: num(&metrics["input_tokens"]),
                output_tokens: num(&metrics["output_tokens"]),
                cache_read_tokens: num(&metrics["cache_read_tokens"]),
                // Devin doesn't split 5m/1h cache writes.
                cache_write_5m_tokens: num(&metrics["cache_creation_tokens"]),
                ttft_ms: num_opt(&metrics["ttft_ms"]).map(|v| v as i64),
                duration_ms: num_opt(&metrics["total_time_ms"]).map(|v| v as i64),
                status: text(&md["finish_reason"]),
                credits: fnum(&md["acu_cost"]),
                provenance: Provenance::LocalSqlite,
                raw_ref: Some(format!("{}#row:{}", item.path.display(), row_id)),
                ..Default::default()
            });
        }
        if (max_row as u64) > cur.offset || cur.state.as_deref() != Some(METRICS_STATE) {
            store.save_cursor(
                self.id(),
                &item.key,
                &item.path,
                max_row as u64,
                0,
                Some(METRICS_STATE),
            )?;
        }
        out.consumed = max_row as u64;
        Ok(out)
    }
}

